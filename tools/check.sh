#!/usr/bin/env bash
# Ровно те же ворота, что стоят в CI (`.github/workflows/deploy.yml`).
#
# Зачем отдельная команда. В `pyproject.toml` стоит `addopts = -m 'not slow'`,
# поэтому `pytest` без аргументов НЕ гоняет медленные тесты, а CI гоняет их
# отдельным шагом. Зелёный локальный прогон при этом ничего не обещает: 3
# ноября 2026 девять медленных тестов движения (`tests/test_motion.py`) три
# часа держали выкладку, пока локально всё было зелёным, и шесть пушей подряд
# не доехали до сервера молча — job `deploy` с `needs: test` не падает, а
# пропускается.
#
#   tools/check.sh          # всё, что проверяет CI
#   tools/check.sh fast     # только быстрые, для итераций
#
# Питон берётся из .venv, переопределяется переменной PY.
set -euo pipefail
cd "$(dirname "$0")/.."
PY=${PY:-.venv/bin/python}
only=${1:-all}

echo "→ быстрые тесты"
"$PY" -m pytest -q
[ "$only" = "fast" ] && { echo "только быстрые — ворота CI этим не пройдены"; exit 0; }

echo "→ типы рендера"
(cd render && npx tsc --noEmit -p .)

# `-rs` печатает причины пропусков: один медленный тест ASR пропускается
# сознательно, и пропуск — это зелёный прогон, а не дыра.
echo "→ медленные тесты (рендер, геометрия, движение, ASR)"
"$PY" -m pytest -q -m slow -rs

echo "всё зелёное — те же проверки, что в CI"
