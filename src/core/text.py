"""Текст слова для экрана.

Пословный субтитр — не транскрипт. Точка после слова в кадре не значит ничего:
пауза уже показана тем, что слово погасло, а запятая посреди крупного шрифта
читается как мусор на стекле. Поэтому пунктуация срезается на границах слова.

Внутренние дефис и апостроф остаются: «кто-то» и «don't» — одно слово, и разрыв
их ломает, а не чистит.
"""

from __future__ import annotations

# Что срезаем по краям слова. Вопросительный и восклицательный знаки оставлены
# намеренно: они несут интонацию, ради которой слово и выделено.
EDGE_PUNCTUATION = ".,…:;—–‑-«»\"“”„'`()[]{}/\\|*_"

# Что никогда не трогаем внутри слова.
KEEP_INSIDE = "-‑'’"


def strip_punctuation(text: str) -> str:
    """Слово без краевой пунктуации. Пустой результат возвращает исходник.

    Пустой результат возможен на слове, которое целиком состоит из знаков
    (ASR иногда отдаёт «—»). Возвращать пустую строку нельзя: слово исчезнет из
    кадра, а индексы в EDL ссылаются на него — контракт сломается.
    """
    cleaned = text.strip().strip(EDGE_PUNCTUATION).strip()
    return cleaned or text.strip()


def display_text(text: str, *, uppercase: bool = False) -> str:
    """Готовая к рисованию форма слова: без пунктуации, с регистром пресета."""
    out = strip_punctuation(text)
    return out.upper() if uppercase else out
