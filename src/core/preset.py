class FontSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    family: str = "Montserrat ExtraBold"
    # Имя файла в assets/fonts — рендер обязан ставить шрифт сам, иначе Chromium
    # подставит дефолт (§5 M5 ⚠).
    file: str | None = None
    weight: int = 800
    size: int = 84  # px при высоте кадра 1920
    uppercase: bool = False
    letter_spacing: float = -0.01  # em


class Colors(BaseModel):
    model_config = ConfigDict(extra="forbid")

    active: str = "#FFFFFF"  # слово, которое звучит сейчас
    past: str = "#FFFFFF"  # уже прозвучало
    ghost: str = "#FFFFFF"  # ещё не прозвучало
    past_opacity: float = 0.72
    # Ф1: место под ещё не прозвучавшее слово резервируется, но самого слова не
    # видно — иначе вся реплика читается вперёд диктора и «пшик» подсвечивает не
    # появление слова, а смену его яркости. Ноль гасит слово, не убирая его из
    # потока: панель не меняет размер, когда слово зазвучит.
    ghost_opacity: float = 0.0
    accent: str = "#FFD54A"
    shout: str = "#FF6A3D"
    outline: str = "#000000"
    shadow: str = "#000000"


class Panel(BaseModel):
    """Панель под текстом. Контейнер растёт под контент сам (M5).

    Здесь ДВА разных слоя, и путать их нельзя.

    `color`/`opacity` — заслонка: тёмная подложка, которой правило контраста
    (Ф9) добирает порог над светлым фоном. Это закон, она приходит сама на любой
    блок, где порог не взят, и её цвет обязан быть тёмным — иначе у правила не
    останется рычага (`test_contrast_rule_has_a_lever_on_every_background`).

    `glass_*` плюс `blur` и рамка — матовое стекло: украшение, которое носят
    только помеченные режиссёром блоки (`CaptionBlock.panel`). В эталоне стекло
    не коррелирует ни с яркостью фона, ни с его суетливостью, то есть работой
    предохранителя оно не является и подчиняться замеру не должно.

    Место под панель — паддинги и рамка — резервируется у ВСЕХ блоков одинаково,
    независимо от флага: иначе текст прыгал бы на её высоту между соседними
    блоками, а Python и Chromium разошлись бы в замере прямоугольника.
    """

    model_config = ConfigDict(extra="forbid")

    enabled: bool = True
    color: str = "#0B0F14"
    opacity: float = 0.34
    blur: int = 18
    radius: int = 30
    padding_x: int = 34
    padding_y: int = 22
    border_color: str = "#FFFFFF"
    border_opacity: float = 0.12
    border_width: int = 1
    # Стекло. Замер эталона: над чёрной футболкой плашка поднимает яркость с 5.6
    # до 41.5 из 255, то есть светлая заливка около 0.14.
    glass_color: str = "#FFFFFF"
    glass_opacity: float = 0.0


# Поля субтитра, которых в модели больше нет, но которые лежат в СОХРАНЁННЫХ
# планах: пресет уезжает в план целиком, а `extra="forbid"` роняет чтение такого
# плана валидацией (`samples/plan-baseline.json` перестал грузиться собственным
# загрузчиком). `max_line_chars` удалён в Ф5: перенос считается в пикселях, а не
# в символах (QUALITY_PLAN). Выкидываем его при чтении молча, а не воскрешаем
# полем-заглушкой — заглушку пресеты начали бы задавать снова, и она бы врала.
REMOVED_CAPTION_FIELDS = ("max_line_chars",)


class Quiet(BaseModel):
    """Тихий регистр субтитра: верхний блок — не уменьшённый плакат, а другой класс.

    Регистров в эталоне ДВА (STYLE_PLAN §1.4.1), и отличаются они не на проценты:

    | | нижний «плакат» | верхний «тихий» |
    |---|---|---|
    | кегль | до 6.2 % высоты кадра | ~1.5 % |
    | золото | одно слово на блок | нет вообще |
    | строк | 1-2 | 4 |
    | выключка | по центру | влево, у левого края |
    | плашка | иногда | нет |

    Пока стиль от позиции не зависел, верхний блок выезжал тем же огромным
    кеглем с золотым словом — то есть плакатом, поставленным наверх.

    Это ДАННЫЕ темы, а не константы кода: регистр есть у pulse и нет у glass и
    bold, и `enabled: false` обязан оставлять их прежний рендер байт в байт.

    Числа — замеры, а не вкус:

    * `font_size` 41 px при кадре 1920: высота глифов Montserrat ExtraBold это
      `cap_height` 0.700 em, то есть 41·0.7 / 1920 = 1.49 % — ровно эталонные
      ~1.5 %. Кеглем задаётся потому, что кегль и есть раскладка (`wrap_block`).
      Калибровка привязана к высоте прописных ОДНОГО шрифта, и выбор другого
      её не ломает: `core.options.apply_font` пересчитывает все три кегля по
      `cap_height` нового шрифта, чтобы оптическая крупность осталась той же.
    * `max_line_width_ratio` 0.30 — узкая колонка, и без неё четырёх строк не
      бывает: эталонное «Я лишь отправляю ему сырое видео» (3.6-5.2 с) это шесть
      слов в ЧЕТЫРЕ строки, то есть ~1.5 слова на строку. На полном бюджете
      плаката (0.74) те же шесть слов кеглем 41 укладываются в одну строку, и
      замер «строк 4» становится невоспроизводимым. При 0.30 (324 px в кадре
      1080) перенос даёт «Я лишь / отправляю / ему сырое / видео» — те самые
      четыре строки.
    * `margin` 140 px: верхний кластер эталона центрирован на 12.9 % высоты, а
      четырёхстрочный тихий блок высотой 220.8 px, прибитый к 140, даёт центр
      13.04 %. Ниже 134 px (`safe_area_ratio`) опускаться всё равно нельзя.
    * `line_height` 1.2 против 1.06 у плаката: межстрочие плаката считано для
      кегля в четыре раза крупнее, на мелком тексте строки от него слипаются.
    * `edge_ratio` 0.18 — единственный измеренный в эталоне левый край (§1.3,
      слово «Бот» верхнего кластера стоит на 18 % ширины). §1.4.1 про тихий блок
      говорит только «влево, у левого края», и брать тут иное число значило бы
      выдумывать.

    Чего здесь НЕТ и почему. Выделения: у тихого блока его нет вовсе — ни
    золота, ни крика, ни увеличенного слова, — поэтому `render_plan` гасит
    выделение самих СЛОВ, а не красит их иначе. Анимации: про вход и уход
    верхнего блока эталон ничего отдельного не говорит, и выдумывать второй
    набор чисел не на чем.
    """

    model_config = ConfigDict(extra="forbid")

    # Выключатель темы. По умолчанию регистра нет: glass и bold рисуют верхний
    # блок так же, как рисовали.
    enabled: bool = False
    # Позиция, которая играет тихо. Одна: в эталоне тихий блок висит наверху, и
    # так же это понимает валидатор EDL (`edl.BLOCK_POSTER_MAX_WORDS` — длинный
    # блок обязан стоять в `top`).
    position: Literal["top", "center", "bottom"] = "top"
    # Кегль и отступ от края — пиксели при высоте кадра 1920 (`_PIXEL_FIELDS`).
    font_size: int = 41
    margin: int = 140
    line_height: float = 1.2
    align: Literal["center", "left"] = "left"
    # К какому краю КАДРА прижат блок (не выключка строк внутри него — это
    # `align`). Плакат центрирован, тихий блок стоит у левого края.
    edge: Literal["center", "left"] = "left"
    edge_ratio: float = 0.18
    max_lines: int = 4
    max_line_width_ratio: float = 0.30
    panel: bool = False

    def plays_at(self, position: str) -> bool:
        """Играет ли блок в этой позиции тихо."""
        return self.enabled and position == self.position

    def left_x(self, frame_width: int) -> float | None:
        """Левый край блока в пикселях кадра; `None` — блок центрирован.

        Одна формула на оба рендерера: Captions.tsx считает `paddingLeft` ею же,
        поэтому прямоугольник плана и бокс в кадре совпадают без округлений.
        """
        return frame_width * self.edge_ratio if self.edge == "left" else None

    def preset(self, base: "Preset") -> "Preset":
        """Пресет тихого регистра: та же тема, другой класс субтитра.

        Отдельный `Preset`, а не горсть параметров, ровно потому, что раскладку
        считает общий код: `wrap_block`, `caption_text_width`, `line_gap`,
        `line_box_height`, `block_rect` и резерв `caption_zone` получают пресет и
        больше ничего не знают. Регистр, выраженный пресетом, проходит через них
        без единой ветки «а если тихий».

        `base` обязан быть уже приведён к высоте кадра (`scaled`): пиксельные
        числа регистра пересчитывает тот же `_PIXEL_FIELDS`, что и остальные.

        Что обнуляется и почему:

        * `fill_max_scale` → 1.0. Рост под ширину строки (С1) — приём плаката; на
          тихом блоке он поднял бы кегль до бюджета колонки и стёр бы весь
          регистр, ради которого всё и делается.
        * `accent_scale`/`shout_scale` → 1.0. У тихого блока выделенного слова
          нет, и резерв `caption_zone` обязан это знать: иначе он уступает
          картинке полосу под крик, которого в этом регистре не бывает.
        * `panel.enabled` — по флагу регистра, но не шире темы: панель без
          паддингов темы нарисовать нечем.
        """
        ps = base.model_copy(deep=True)
        ps.font.size = self.font_size
        ps.caption.margin = self.margin
        ps.caption.line_height = self.line_height
        ps.caption.align = self.align
        ps.caption.max_lines = self.max_lines
        ps.caption.fill_max_scale = 1.0
        ps.geometry.max_line_width_ratio = self.max_line_width_ratio
        ps.panel.enabled = self.panel and base.panel.enabled
        ps.animation.accent_scale = 1.0
        ps.animation.shout_scale = 1.0
        return ps


class TitleCard(BaseModel):
    """Титр первых секунд: самый крупный текст ролика (STYLE_PLAN §5).

    Третий регистр субтитра. Устроен он как ПЛАКАТ, поднятый наверх, — подпись
    мелкой строкой и одно огромное слово под ней, — но числа у него свои, и
    выше плакатных: в эталоне титр набран кеглем, которого в субтитрах не
    бывает нигде.

    Замеры эталона (`style-showcase.mp4`, 464×848, 30 fps), по маске яркого
    текста в верхней трети кадра:

    * живёт 0.13-1.30 с, дальше гаснет за кадр-два;
    * занимает полосу 16.98-27.59 % высоты кадра;
    * высота глифов большого слова 10.1 % высоты кадра (148..233.5 px) — потолок
      плаката в том же ролике 7.5 %, то есть титр крупнее ЛЮБОГО субтитра;
    * подпись над ним — 2.36 % (144..163 px), то есть вчетверо мельче;
    * строки ЗАХОДЯТ друг на друга: базовые линии отстоят на 71 px при кегле
      большого слова 122 px, то есть межстрочие 0.58 от кегля;
    * собирается по слову, как обычный блок: 324 → 664 → 1049 → 1692 пикселей
      маски с шагом 0.1 с, место под ещё не пришедшее слово зарезервировано
      (левый край подписи не шевелится, §1.3);
    * золота в нём НЕТ: медиана по маске глифов #FDFAF2 — цвет обычного слова,
      а не акцентный #F3D28F (§1.2).

    Числа ниже — пересчёт этих замеров на кадр 1920 (`_PIXEL_FIELDS`):

    * `font_size` 65: высота глифов подписи это `cap_height` 0.700 em, и
      65·0.7/1920 = 2.37 % — эталонные 2.36 %.
    * `accent_scale` 4.25: 65·4.25 = 276 px, глифы 276·0.7/1920 = 10.06 % —
      эталонные 10.1 %. Выделение в титре несёт РАЗМЕР, а не цвет, поэтому
      акцентный цвет регистр подменяет на цвет обычного слова (`preset`).
    * `line_height` 0.5: подъём бокса над базовой линией равен `F·(lh/2+0.3585)`
      (см. `geometry.line_box_height`), и при 0.5 базовые линии двух строк
      отстоят на 161.0 px при эталонных 71·1920/848 = 160.8, а полоса титра
      выходит 206.6 px — 10.76 % высоты кадра против эталонных 10.7 %. При
      межстрочии плаката (1.06) та же полоса вышла бы 306 px, 15.9 %: большое
      слово стояло бы ПОД подписью, а не заходило на неё.
    * `margin` 332: подпись начинается на `margin − 5.95` (её глифы торчат над
      своим боксом при таком межстрочии), и 326 px это ровно 17.0 % высоты.

    Это ДАННЫЕ темы, а не константы кода: титр есть у pulse и нет у glass и
    bold, и `enabled: false` обязан оставлять их рендер прежним.
    """

    model_config = ConfigDict(extra="forbid")

    # Выключатель темы. По умолчанию титра нет.
    enabled: bool = False
    # Когда титр появляется и сколько живёт — секунды ВЫХОДНОГО таймлайна.
    # Ролик короче — титра не будет (`render_plan`): обрезанный титр читается
    # как сбой, а не как титр.
    start: float = 0.2
    duration: float = 1.1
    # Через сколько приходит следующее слово. 0.1 с — замер эталона; шаг
    # ужимается, если слов столько, что последнее иначе не успело бы встать.
    word_step: float = 0.1
    # Кегль подписи и отступ от верха кадра — пиксели при высоте кадра 1920.
    font_size: int = 65
    margin: int = 332
    # Во сколько раз большое слово крупнее подписи.
    accent_scale: float = 4.25
    line_height: float = 0.5
    # Строк ровно две: подпись и слово под ней. Третья строка — это уже не титр,
    # а абзац наверху кадра, и такой титр `render_plan` не ставит вовсе.
    max_lines: int = 2
    # Бюджет строки — вся безопасная ширина кадра: при 1.0 строку зажимает
    # только безопасная зона (`geometry.caption_text_width` вычитает её сам).
    # Доля плаката (0.74 у pulse) сюда не годится — это место ПОД плашку и вкус
    # темы, а титр стоит без плашки и один в своей полосе. Замер эталона это
    # подтвердить не может и не опровергает: там титр занимает 58 и 65 % ширины,
    # то есть до любого из двух потолков не достаёт.
    max_line_width_ratio: float = 1.0
    panel: bool = False

    def preset(self, base: "Preset") -> "Preset":
        """Пресет титра: та же тема с подменёнными числами.

        Отдельный `Preset` по той же причине, что и у тихого регистра
        (`Quiet.preset`): раскладку считает общий код — `wrap_block`,
        `caption_text_width`, `line_gap`, `line_box_height`, `block_rect`, — и
        регистр, выраженный пресетом, проходит через него без единой ветки «а
        если титр».

        `base` обязан быть уже приведён к высоте кадра (`scaled`).

        Что подменяется сверх очевидного и почему:

        * `fill_max_scale` → 1.0. Рост под ширину строки (С1) — приём плаката;
          у титра размер ИЗМЕРЕН, а не подобран, и подгонка под строку стёрла бы
          замер.
        * `colors.accent`/`colors.shout` → цвет обычного слова. В титре эталона
          золота нет ни одного пикселя (#FDFAF2 против #F3D28F у акцента), а
          выделение всё равно нужно — им в титре задан КЕГЛЬ большого слова.
        * `panel.enabled` — по флагу регистра, но не шире темы: без паддингов
          темы плашку рисовать нечем. У титра её нет, и место под неё поэтому не
          резервируется — иначе полоса титра уехала бы вниз на 48 px.
        """
        ps = base.model_copy(deep=True)
        ps.font.size = self.font_size
        ps.caption.margin = self.margin
        ps.caption.line_height = self.line_height
        ps.caption.max_lines = self.max_lines
        ps.caption.fill_max_scale = 1.0
        ps.geometry.max_line_width_ratio = self.max_line_width_ratio
        ps.panel.enabled = self.panel and base.panel.enabled
        ps.animation.accent_scale = self.accent_scale
        ps.animation.shout_scale = self.accent_scale
        ps.colors.accent = base.colors.active
        ps.colors.shout = base.colors.active
        return ps


class Caption(BaseModel):
    model_config = ConfigDict(extra="forbid")

    @model_validator(mode="before")
    @classmethod
    def _drop_removed_fields(cls, data: object) -> object:
        if isinstance(data, dict) and any(k in data for k in REMOVED_CAPTION_FIELDS):
            return {k: v for k, v in data.items() if k not in REMOVED_CAPTION_FIELDS}
        return data

    position: Literal["top", "center", "bottom"] = "bottom"
    # Отступ от края кадра в пикселях при высоте 1920.
    margin: int = 360
    line_height: float = 1.06
    align: Literal["center", "left"] = "center"
    # Сколько строк максимум в блоке. Не влезло — блок ужимается целиком, а не
    # переполняет контейнер (Ф5).
    max_lines: int = 3
    # Пол кегля при ужатии: доля от кегля строки. Ниже него текст перестаёт
    # быть субтитром, поэтому переполнение честнее, чем микроскопия. 0.4 — не
    # вкус, а замер: самый широкий глиф кириллицы в Montserrat ExtraBold — «Щ»
    # (1.135 em; «Ж» 1.109, «Ш» 1.099), и на поле 0.4 в бюджет строки bold
    # влезает 18 таких подряд, а девятнадцатый вылезает
    # (см. test_word_wider_than_the_floor_overflows_knowingly).
    #
    # ⚠ Замер сделан под ОДИН шрифт, а шрифт теперь выбирает пользователь
    # (`core.options.FONTS`). У других «Щ» другой: Oswald SemiBold 0.867 em,
    # Golos Text 1.035, Playfair 1.165, Unbounded 1.461 — то есть на Unbounded
    # этот пол значит почти на треть больше ширины, чем на Montserrat. Число
    # осталось свойством ТЕМЫ, а не шрифта, сознательно: оно про «ниже этого
    # текст не читается», а не про «столько-то букв влезает». Если на широком
    # шрифте начнёт переполнять — чинить здесь, а не нормировкой.
    min_word_scale: float = 0.4
    # Потолок РОСТА блока: во сколько раз кегль слова может подняться над
    # кеглем пресета, добирая ширину строки (С1). 1.0 — блок не растёт вовсе,
    # то есть прежнее поведение, и это дефолт: рост включает тема, а не код.
    #
    # Зачем рост. У эталона (`STYLE_PLAN.md`) кегль акцента не задан числом, а
    # подобран под строку: «также» из пяти букв набрано вдвое крупнее, чем
    # «звуковые» из восьми, и строка в обоих случаях добирает 65-83 % ширины
    # кадра. Фиксированным кеглем это не выражается — при 88 px наша строка
    # занимает 27 % ширины и иерархии в кадре не читается.
    fill_max_scale: float = 1.0
    # Есть ли у блока ОДИН дом по вертикали. Пока блок волен встать и наверху, и
    # внизу, картинке приходится уступать обе полосы сразу — а с выросшим
    # блоком (`fill_max_scale`) на две полосы кадра просто не хватает, и любая
    # вставка становится полноэкранной. Пришпиленный блок уступает одну полосу,
    # и карточка снова помещается.
    #
    # Уклонение при этом не теряется: картинка всё равно обходит субтитр
    # (`broll_free_band`), а двигать сам блок нужно было только затем, чтобы
    # разойтись с ней же.
    pinned: bool = False
    # Второй регистр субтитра — тихий верхний блок (§1.4.1). Всё остальное в
    # этой секции описывает ПЛАКАТ, то есть нижний регистр.
    quiet: Quiet = Field(default_factory=Quiet)
    # Третий регистр — титр первых секунд (STYLE_PLAN §5). Его текст приходит не
    # из речи, а из заголовка ролика (`EDL.title`), поэтому в блоках EDL его
    # нет: титр собирает `render_plan`.
    title_card: TitleCard = Field(default_factory=TitleCard)


