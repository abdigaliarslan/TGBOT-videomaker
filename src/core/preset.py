class Contrast(BaseModel):
    """Контраст как ограничение, а не как вкус (Ф9).

    Панель фиксированной прозрачности не справляется над светлым фоном: белый
    текст на светлой стене читается хуже, чем на тёмной, при одних и тех же
    числах пресета. Препроцесс кладёт в блок `bg_luma` — среднюю яркость под
    ним, — а рендерер по этим двум опорным точкам ведёт панель и цвет текста
    между «над тёмным» и «над светлым».

    Опорные точки — это стиль. Порог `min_ratio` — это закон: если между
    точками контраст всё равно ниже него, рендерер поднимает прозрачность
    панели ровно настолько, чтобы порог был взят. `bg_luma = null` (никто не
    мерил) выключает всё правило целиком, и пресет играет как играл.
    """

    model_config = ConfigDict(extra="forbid")

    enabled: bool = True
    # Контраст по WCAG. Для крупного жирного текста порог AA равен 3.0; берём
    # 4.5 — субтитр читают в движении и часто на телефоне на солнце.
    min_ratio: float = 4.5
    # Яркости опорных точек (0..1). Между ними всё интерполируется линейно,
    # снаружи — зажимается.
    luma_dark: float = 0.2
    luma_light: float = 0.8
    panel_opacity_dark: float = 0.5
    panel_opacity_light: float = 0.86
    # Цвет обычного слова (active/past/ghost) в опорных точках. Акцент и крик
    # сохраняют свой цвет: это опознавательный знак стиля, а не читаемость.
    text_dark: str = "#FFFFFF"
    text_light: str = "#FFFFFF"


class Animation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # Появление слова: пружина (Remotion) / линейный масштаб (ASS).
    pop_scale: float = 1.16
    pop_ms: int = 160
    spring_damping: float = 12.0
    spring_stiffness: float = 190.0
    spring_mass: float = 0.7
    block_in_ms: int = 180
    # Сколько блок живёт ПОСЛЕ своего конца: столько же длится его уход и
    # столько же уходящий и приходящий блоки лежат в кадре вместе. Пресет просит
    # 100-140 мс, но нахлёст короче `block_overlap_min_ms` даёт между репликами
    # пустой кадр, поэтому фактический хвост — максимум из этих двух чисел.
    # Оба живут здесь, а не константами в TSX: §0.3, пресет — данные.
    block_out_ms: int = 140
    block_overlap_min_ms: int = 220
    # Насколько круче альфы уходящего блока падает кривая прихода и до какого
    # масштаба он ужимается, пока уходит. Не стилевые числа: они разводят два
    # текста, лежащих в одном месте кадра во время нахлёста. Показатель 1.35
    # опускает максимум одновременной читаемости с 0.50 до 0.448 (замер по
    # кривой, а не по кадровой сетке), а сумма альф в точке пересечения падает
    # с 1.00 всего до 0.90 — то есть кадр не проваливается в пустоту.
    block_leave_falloff: float = 1.35
    block_leave_scale: float = 0.9
    # Пауза с ПУСТЫМ экраном между блоками (С4). Больше нуля — блок уходит ДО
    # своего конца, нахлёста нет вовсе, и всё, что написано выше про разведение
    # двух текстов, к такому пресету не относится. Ноль — прежнее поведение.
    #
    # Эталон делает первое: между блоками у него три кадра без текста вообще
    # (замерено на кадрах 165-167), и ни одного стыка с нахлёстом.
    block_gap_ms: int = 0
    # Наезд блока на входе. Ноль — масштабной анимации нет: у эталона ширина
    # слова с первого же видимого кадра финальная.
    block_in_zoom: float = 0.035
    accent_scale: float = 1.18
    shout_scale: float = 1.34
    shout_rotate: float = -4.0  # градусы
    # Ход движения в пикселях при высоте кадра 1920. Раньше эти два числа были
    # константами в TSX (`font.size * 0.28` и `height * 0.09`) и Python о них не
    # знал; здесь они данные, которые пересчитывает scaled().
    block_shift_px: int = 24  # подъём блока субтитров на входе
    # Уход блока на выходе. Больше входа в разы, и это не вкус: блоки идут
    # встык, поэтому уходящий и приходящий блок ЛЕЖАТ ДРУГ НА ДРУГЕ всё время
    # нахлёста. Одной прозрачностью это не лечится: в точке пересечения кривых
    # обе не ниже 0.4 (сумма обязана держаться около единицы, иначе кадр
    # моргает), и два текста читаются одновременно — замерено на кадре 228
    # эталонного прогона. Развести их может только смещение, и оно должно быть
    # порядка междустрочия, а не 24 px входа.
    block_leave_px: int = 64
    broll_slide_px: int = 173  # ход карточки в slide_up
    # Ken Burns на вставке (М3): насколько картинка наезжает за всю свою жизнь и
    # насколько при этом сползает. Доли, не пиксели: сдвиг считается от высоты
    # кадра, поэтому от разрешения не зависит и в `_PIXEL_FIELDS` не входит.
    # Числа маленькие намеренно — больше 6 % масштаба за две секунды читаются
    # уже как зум, а не как жизнь в кадре.
    kb_scale: float = 0.04
    kb_shift_ratio: float = 0.012
    # Вход вставки (Broll.tsx): за сколько картинка проступает и из какого
    # расфокуса. Расфокус — доля высоты кадра, а не пиксели, поэтому в
    # `_PIXEL_FIELDS` не входит. Наезд длится вдвое дольше: картинка сначала
    # появляется, потом садится на место.
    broll_in_ms: int = 600
    broll_in_blur: float = 0.012
    # Лёгкий перелёт входа карточки и угловой вставки: доля масштаба, на которую
    # картинка проскакивает единицу, прежде чем сесть на место. Ноль — прежнее
    # поведение, монотонный подъём; старые планы от появления поля не меняются.
    #
    # Поле заведено после того, как монотонные безье убрали вместе с прыжком и
    # всю упругость: картинка приезжала мёртвой. До них вход вела пружина, она
    # проскакивала на 4-7 % и карточка видимо подпрыгивала (AUDIT §8.3) —
    # поэтому перелёт вернулся ОГРАНИЧЕННЫМ сверху числом пресета, а не
    # пружиной, у которой амплитуда следствие жёсткости и массы.
    #
    # Доля, а не пиксели: в `_PIXEL_FIELDS` не входит. Полноэкранного наезда
    # (1.08 → 1) поле не касается — там перелёт уводит масштаб НИЖЕ единицы, и
    # за краями картинки показывается исходное видео.
    #
    # Потолок — не вкус, а геометрия. Перелёт масштаба двигает КАЖДЫЙ край
    # карточки на половину амплитуды, а место покоя ей считает
    # `core/geometry.py` по свободной полосе кадра и разводит с субтитром по
    # прямоугольникам — трансформа он не видит. На эталонном прогоне при 0.03
    # край уходит на 5.3 px и до полосы субтитра остаётся 48.7 px из 54; при
    # 0.05 запас съедается вдвое. Выше — в субтитр, поэтому `le`.
    #
    # Низ закрыт по другой причине: отрицательное значение `Broll.tsx` молча
    # игнорирует (там `overshoot > 0`), а пробник `card_probe.mjs` честно
    # посчитает отрицательную горку, и замер разойдётся с кадром.
    broll_overshoot: float = Field(default=0.0, ge=0.0, le=0.05)
    # Вспышка света (light leak) на входе полноэкранной вставки: засвет плёнки
    # прикрывает сам рез, и смена картинки читается как монтажный переход, а не
    # как подмена кадра. Ноль — вспышки нет: прежнее поведение, старые планы
    # от появления поля не меняются. Оттенок — поворот цвета в градусах от
    # жёлто-оранжевого (0), 240 — синий.
    leak_ms: int = 0
    leak_hue: float = 0.0
    # Сколько слово ПРОЯВЛЯЕТСЯ, когда прозвучало. Ноль — мгновенно, за один
    # кадр: прежнее поведение, и старые планы от появления поля не меняются.
    #
    # У эталона проявление занимает 4 кадра (~130 мс, замерено по яркости слова
    # «вставляет» на 8.9-9.2 с): слово набирает силу, место под него
    # зарезервировано заранее, соседи не шевелятся. Это единственное
    # расхождение с эталоном, оставшееся после С1-С6.
    word_in_ms: int = 0
    # Насколько слово выезжает снизу, пока проявляется. Пиксели кадра 1920.
    #
    # Только `transform`: раскладку (кегль, трекинг, ширины строк) считает
    # Python и сверяет с Chromium с точностью 2 px, поэтому двигать слово
    # можно, а менять его метрику — нельзя, иначе разъедется перенос.
    word_rise_px: int = 0


# Все поля пресета, измеренные в пикселях при высоте кадра 1920. Держим их одним
# списком: появилось новое пиксельное поле — впиши сюда, иначе на превью 720p оно
# останется в масштабе 1920 и композиция поедет. Всё, чего здесь нет, от высоты
# кадра не зависит по своей природе: миллисекунды, множители, доли, цвета.
#
# Секция пишется путём через точку: пиксели есть и у вложенного тихого регистра
# (`caption.quiet`), а он тоже обязан уезжать на превью целиком — кегль 41 px,
# оставленный в масштабе 1920, на кадре 960 стал бы вдвое крупнее задуманного и
# верхний блок перестал бы быть тихим.
_PIXEL_FIELDS: tuple[tuple[str, str], ...] = (
    ("font", "size"),
    ("caption", "margin"),
    ("caption.quiet", "font_size"),
    ("caption.quiet", "margin"),
    ("caption.title_card", "font_size"),
    ("caption.title_card", "margin"),
    ("panel", "padding_x"),
    ("panel", "padding_y"),
    ("panel", "radius"),
    ("panel", "blur"),
    ("panel", "border_width"),
    ("animation", "block_shift_px"),
    ("animation", "block_leave_px"),
    ("animation", "broll_slide_px"),
    ("animation", "word_rise_px"),
)

# Поля, которые округляются ВНИЗ, а не к ближайшему.
#
# Кегль решает перенос строк, а бюджет строки (`geometry.caption_text_width`)
# считается от ширины кадра в float и масштабируется точно. Округлённый вверх
# кегль растёт относительно бюджета — 88 → 59 при k = 0.6667 это +0.57 % — и
# строка, влезавшая на 1080p с запасом в доли процента, на превью 720p
# переносится. Замерено на эталонном прогоне: «не стоит бежать» — одна строка в
# 1080p и две в 720p, то есть композиция превью не совпадает с финалом.
# Вниз кегль относительно бюджета только уменьшается, поэтому перенос на меньшем
# кадре может стать разве что свободнее, но не теснее.
_ROUND_DOWN: frozenset[tuple[str, str]] = frozenset(
    {("font", "size"), ("caption.quiet", "font_size"), ("caption.title_card", "font_size")}
)


def _section(root: object, path: str) -> object:
    """Секция пресета по пути через точку (`caption.quiet`)."""
    node = root
    for part in path.split("."):
        node = getattr(node, part)
    return node


class Preset(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    title: str = ""
    # Место темы в ленте выбора. Тем стало много, и алфавит ставил бы рядом
    # вещи, которые рядом не стоят: сначала идут четыре выверенные по эталону,
    # потом наборные. Умолчание большое, чтобы тема без поля встала в конец, а
    # не влезла в начало.
    order: int = 100
    font: FontSpec = Field(default_factory=FontSpec)
    colors: Colors = Field(default_factory=Colors)
    panel: Panel = Field(default_factory=Panel)
    caption: Caption = Field(default_factory=Caption)
    animation: Animation = Field(default_factory=Animation)
    geometry: Geometry = Field(default_factory=Geometry)
    contrast: Contrast = Field(default_factory=Contrast)
    grade: Grade = Field(default_factory=Grade)
    crop: Crop = Field(default_factory=Crop)
    audio: Audio = Field(default_factory=Audio)
    background: str = "#000000"

    def scaled(self, height: int) -> "Preset":
        """Размеры заданы для 1920 по высоте; под другой кадр — пропорционально.

        Пересчитывается всё пиксельное разом по `_PIXEL_FIELDS`. Раньше список
        был зашит в тело метода и покрывал шесть полей из девяти: рамка панели и
        ход анимаций оставались в масштабе 1920 и на превью 720p прыгали в
        полтора раза сильнее остальной композиции.
        """
        if height == 1920:
            return self
        k = height / 1920
        clone = self.model_copy(deep=True)
        for section, name in _PIXEL_FIELDS:
            value = getattr(_section(self, section), name)
            # Ноль — это «выключено», он остаётся нулём. А единица это не размер,
            # а волосок: округление в ноль стирает край панели совсем.
            if value == 0:
                fresh = 0
            elif (section, name) in _ROUND_DOWN:
                fresh = max(1, int(value * k))
            else:
                fresh = max(1, round(value * k))
            setattr(_section(clone, section), name, fresh)
        # Ниже 12 px текст перестаёт быть субтитром на любом кадре. Пол стоит по
        # эту сторону, до выгрузки в план: рендерер читает уже зажатое число, и
        # разойтись с замером Python ему негде.
        clone.font.size = max(12, clone.font.size)
        clone.caption.quiet.font_size = max(12, clone.caption.quiet.font_size)
        clone.caption.title_card.font_size = max(12, clone.caption.title_card.font_size)
        return clone


def available() -> list[str]:
    return sorted(p.stem for p in PRESETS_DIR.glob("*.json"))


@lru_cache(maxsize=32)
def load_preset(name: str) -> Preset:
    path = PRESETS_DIR / f"{name}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"нет пресета {name!r}; доступны: {', '.join(available()) or '—'}"
        )
    data = json.loads(path.read_text(encoding="utf-8"))
    data.setdefault("name", name)
    return Preset(**data)


