/**
 * Пол длительности анимации в кадрах.
 *
 * Короче восьми кадров глаз читает переход не как движение, а как мигание:
 * motion blur рендерер не рисует, и вся анимация вырождается в две-три
 * ступеньки (§8.3 аудита: видимое движение картинки — 3 кадра, 90 мс).
 * Поэтому длительности из пресета — пожелание, а восемь кадров — закон.
 */
export const MIN_ANIM_FRAMES = 8;

/** Миллисекунды пресета → кадры, но не короче порога восприятия. */
export const animFrames = (ms: number, fps: number): number =>
  Math.max(MIN_ANIM_FRAMES, Math.round((ms / 1000) * fps));

/**
 * То же, но БЕЗ порога в восемь кадров — для чистой прозрачности.
 *
 * `MIN_ANIM_FRAMES` — правило про ДВИЖЕНИЕ: короткий ход не читается как ход и
 * выглядит щелчком. К проявлению это не относится: у эталона блок появляется за
 * три кадра и уходит за два (замерено по яркости внутри силуэта глифов —
 * 0.25 / 0.60 / 1.00), и восьмикадровый пол сделал бы такое появление
 * невозможным втрое.
 */
export const fadeFrames = (ms: number, fps: number): number =>
  Math.max(1, Math.round((ms / 1000) * fps));

export type SpringConfig = { damping: number; stiffness: number; mass: number };

/**
 * Натуральная длительность пружины в кадрах.
 *
 * `durationInFrames` короче натуральной сжимает пружину по времени и обрывает
 * её на максимуме скорости — вместо упругости выходит рывок (§8.3: задано
 * 10 кадров при 18 натуральных). `measureSpring` кеширует результат внутри
 * себя, так что вызывать его на каждом кадре дёшево.
 */
export const springFrames = (fps: number, config: SpringConfig): number =>
  Math.max(MIN_ANIM_FRAMES, measureSpring({ fps, config }));

/**
 * Плавная ступенька 0 → 1 с нулевой производной на ОБОИХ концах.
 *
 * `easeOut` тормозит только к концу, а стартует с максимальной скоростью
 * (производная 3), поэтому склеивать из него горку нельзя: подъём щёлкает в
 * начале, а на вершине два куска сходятся углом.
 */
const smoothStep = (t: number): number => {
  const x = Math.max(0, Math.min(1, t));
  return x * x * (3 - 2 * x);
};

/**
 * Транзиентный «пшик»: 0 → 1 → 0 по нормированному времени.
 *
 * Считается по времени, а не по значению пружины: на пружине пик приходился
 * на третий кадр, то есть на два кадра всей заметной фазы.
 *
 * Обе половины — `smoothStep`, и `rise` близок к половине окна. Это не вкус, а
 * следствие `MIN_ANIM_FRAMES`: закон меряет ВСЮ анимацию, а глаз — её самую
 * быструю фазу. На `easeOut` с `rise = 0.35` подъём занимал 2.8 кадра из
 * восьми, и первый же кадр съедал 73 % амплитуды (замер: 0 → 0.734 → 0.977) —
 * то есть пол в восемь кадров формально соблюдался, а щелчок оставался на
 * месте. Теперь ни один кадр не берёт больше 40 % (0.189 / 0.394 / 0.343 / …),
 * и подъём длится 3.6 кадра из восьми: атака ещё читается как рывок, но уже не
 * как ступенька.
 */
export const popBump = (q: number, rise = 0.45): number => {
  if (q <= 0 || q >= 1) return 0;
  return q < rise ? smoothStep(q / rise) : 1 - smoothStep((q - rise) / (1 - rise));
};

/**
 * Числа анимации приезжают из пресета, а не из констант в TSX (§0.3).
 * Пиксельные из них пересчитывает под высоту кадра `Preset.scaled(height)`;
 * миллисекунды и множители от высоты не зависят.
 *
 * Читаются через запасное значение: план, собранный пресетом без этого поля
 * (сохранённый лист, чужой инструмент), обязан рендериться по-старому, а не
 * падать на `undefined`. Ключи берутся из самого типа пресета — новое поле в
 * `types.ts` становится доступно здесь само.
 */
type AnimNumbers = {
  [K in keyof Preset["animation"] as undefined extends Preset["animation"][K]
    ? K
    : never]: Preset["animation"][K];
};

export const animNum = (
  animation: Preset["animation"],
  key: keyof AnimNumbers,
  fallback: number,
): number => {
  const value = animation[key];
  return typeof value === "number" ? value : fallback;
};

/** То же самое для пиксельных полей: имя оставлено ради читаемости на месте. */
export const motionPx = animNum;
